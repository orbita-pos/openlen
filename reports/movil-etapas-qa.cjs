const { chromium, expect } = require('@playwright/test');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const salida = path.resolve('reports/movil-etapas'); fs.mkdirSync(salida, { recursive: true });
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, screen: { width: 390, height: 844 }, locale: 'es-MX', isMobile: true, hasTouch: true });
  const page = await context.newPage();
  const errores = []; page.on('pageerror', e => errores.push(e.message));
  const foto = nombre => page.screenshot({ path: path.join(salida, nombre + '.png'), animations: 'disabled' });
  try {
    await page.goto('http://127.0.0.1:5175/?muestra=1');
    await expect(page.getByRole('button', { name: 'Publicar y gestionar', exact: true })).toBeVisible();
    await foto('01-principal');
    await page.getByRole('button', { name: 'Antes / Ahora', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Antes / Ahora' })).toBeVisible();
    await expect(page.frameLocator('iframe[title="Ahora"]').getByText('Un buen día empieza con pan.')).toBeVisible();
    await foto('02-comparacion-ahora');
    await page.getByRole('button', { name: 'Antes', exact: true }).click();
    await expect(page.frameLocator('iframe[title="Antes"]').getByText('El pan de cada día.')).toBeVisible();
    await foto('03-comparacion-antes');
    await page.getByRole('button', { name: 'Cerrar', exact: true }).click();
    await page.getByRole('button', { name: 'Publicar y gestionar', exact: true }).click();
    await expect(page.locator('.gestion-url')).toContainText('panaderia-luna.example');
    await foto('04-publicar');
    await page.getByRole('button', { name: 'Tus números', exact: true }).click();
    await expect(page.locator('.gestion-numeros')).toContainText('312');
    await foto('05-numeros');
    await page.getByRole('button', { name: 'Encargos', exact: true }).click();
    await foto('06-encargos');
    await page.getByRole('button', { name: 'Cerrar', exact: true }).click();
    await page.getByRole('button', { name: 'Tu Len', exact: true }).click();
    await page.getByRole('button', { name: 'Chef', exact: true }).click();
    await foto('07-tu-len');
    await page.getByRole('button', { name: 'Aplicar', exact: true }).click();
    if (await page.evaluate(() => JSON.parse(localStorage.getItem('len-movil-look')).cabeza) !== 'chef') throw new Error('Look no persistido');
    await page.getByRole('button', { name: /Panadería Luna/ }).click();
    await expect(page.locator('.len-avisos')).toContainText('no están');
    await foto('08-avisos');
    await page.getByRole('button', { name: 'Modo oscuro', exact: true }).click();
    await page.getByRole('button', { name: 'Encoger', exact: false }).click();
    await foto('09-oscuro');
    await page.setViewportSize({ width: 360, height: 640 });
    await page.getByRole('button', { name: /Panadería Luna/ }).click();
    await page.locator('.app-selector .lm-body').evaluate(el => { el.scrollTop = el.scrollHeight; });
    await foto('10-pantalla-compacta');
    await expect(page.getByRole('button', { name: 'Salir', exact: true })).toBeInViewport();
    if (await page.locator('.app-selector').evaluate(el => getComputedStyle(el).touchAction) !== 'pan-y') throw new Error('El gesto impide desplazar la hoja');
    if (errores.length) throw new Error(errores.join('\n'));
    console.log('QA visual: 10 capturas; comparación, publicación, números, encargos, personalización persistida, avisos sin Firebase, tema oscuro y pantalla compacta. Sin errores JavaScript.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
