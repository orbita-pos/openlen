// THE FIGURE ENGINE AS A PUBLISHED FILE (spec local 2026-11-10-figuras-del-asistente, §5.7): a published page's
// bubble asks for the engine only when the visitor opens it, as a file of the site's own release named by its
// content. Publishing must not bundle anything, so the bundle is made HERE and kept in the repo, in
// lib/figure/engine/published.ts — run this after any change to the engine:
//
//   npm run figure:engine            writes it
//   npm run figure:engine -- --check exits 1 when what is kept is not what the engine builds to (a test runs this)
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(root, "lib/figure/engine/published.ts");

export async function builtEngine() {
  const result = await build({
    entryPoints: [path.join(root, "lib/figure/engine/index.ts")],
    bundle: true,
    minify: true,
    format: "iife",
    globalName: "OpenLenFigure",
    // What the bubble calls once the file has loaded.
    footer: { js: "window.__openlenFigure=OpenLenFigure;" },
    target: "es2020",
    legalComments: "inline",
    write: false,
  });
  const code = result.outputFiles[0].text;
  const file = `figure-${createHash("sha256").update(code).digest("hex").slice(0, 8)}.js`;
  const source =
    "// GENERATED by `npm run figure:engine` (scripts/figure-engine-build.mjs) from lib/figure/engine/. Do not edit:\n" +
    "// change the engine and run it again. The published bubble's file, named by its content.\n" +
    `export const FIGURE_ENGINE = { file: ${JSON.stringify(file)}, code: ${JSON.stringify(code)} } as const;\n`;
  return { file, source };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { file, source } = await builtEngine();
  if (process.argv.includes("--check")) {
    const kept = await readFile(target, "utf8").catch(() => "");
    if (kept.replace(/\r\n/g, "\n") !== source) {
      console.error("[figure:engine] lib/figure/engine/published.ts is not what the engine builds to. Run: npm run figure:engine");
      process.exit(1);
    }
    console.log(`[figure:engine] up to date (${file})`);
  } else {
    await writeFile(target, source);
    console.log(`[figure:engine] wrote ${file}`);
  }
}
